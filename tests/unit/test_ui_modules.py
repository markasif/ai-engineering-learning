import os
import re
from pathlib import Path
from html.parser import HTMLParser
import pytest

class AssetParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.assets = []
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        attr_dict = dict(attrs)
        if "id" in attr_dict:
            self.ids.add(attr_dict["id"])
        for k in ("src", "href"):
            if k in attr_dict:
                val = attr_dict[k]
                if val and not val.startswith(("http:", "https:", "#", "data:")):
                    self.assets.append((tag, k, val))

def test_ui_index_html_assets_exist():
    ui_dir = Path("ui")
    index_html = ui_dir / "index.html"
    assert index_html.exists()

    content = index_html.read_text(encoding="utf-8")
    parser = AssetParser()
    parser.feed(content)

    assert len(parser.ids) > 20
    assert len(parser.assets) > 0

    missing = []
    for tag, k, val in parser.assets:
        clean_path = val.split("?")[0]
        full_path = ui_dir / clean_path
        if not full_path.exists():
            missing.append(f"<{tag} {k}='{val}'> -> {full_path}")

    assert not missing, f"Missing referenced assets: {missing}"

