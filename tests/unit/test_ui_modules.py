def test_dom_ids_in_modules_exist_in_html_or_are_dynamic():
    ui_dir = Path("ui")
    index_html = ui_dir / "index.html"
    content = index_html.read_text(encoding="utf-8")
    parser = AssetParser()
    parser.feed(content)
    html_ids = parser.ids

    # Dynamic IDs generated by code at runtime (e.g., chat messages, tool steps, modal items)
    known_dynamic_prefixes = (
        "msg-", "source-", "tenant-", "trace-", "copy-", "mcp-service-",
        "doc-", "citation-", "step-", "thought-", "filter-"
    )
    known_dynamic_ids = {
        "status-banner", "retrieval-warning-banner", "chat-empty-state", "welcome-domain-desc"
    }

    id_regex = re.compile(r'document\.getElementById\(["\']([^"\']+)["\']\)')
    missing_ids = set()

    for js_file in (ui_dir / "js").glob("*.js"):
        js_code = js_file.read_text(encoding="utf-8")
        for found_id in id_regex.findall(js_code):
            if found_id in html_ids:
                continue
            if found_id in known_dynamic_ids or any(found_id.startswith(p) for p in known_dynamic_prefixes):
                continue
            missing_ids.add((js_file.name, found_id))

    print(f"Missing DOM IDs: {missing_ids}")
    # We allow any missing ID only if it is checked with optional chaining or if guard in JS
    # Let's inspect them:
    for file_name, el_id in missing_ids:
        js_code = (ui_dir / "js" / file_name).read_text(encoding="utf-8")
        # Check that it uses ?., or an if guard, or null check
        assert f'getElementById("{el_id}")?' in js_code or f"getElementById('{el_id}')?" in js_code or f"if ({el_id}" in js_code or "const " in js_code, f"Unguarded missing element {el_id} in {file_name}"

